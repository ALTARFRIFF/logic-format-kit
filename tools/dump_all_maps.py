#!/usr/bin/env python3
"""
dump_all_maps.py — build a parameter map for every Audio Unit installed on this
Mac, using tools/au_dump.

This is the general answer to "which float is which parameter": Logic stores a
plug-in's state as one value per AU parameter, in the AU's own order, so the
AU's parameter list *is* the map.  No reverse engineering needed per plug-in.

    python3 tools/dump_all_maps.py [--out param-maps] [--only SUBSTR]

Each AU gets its own file named <manufacturer>_<subtype>.txt.
"""

from __future__ import annotations

import argparse
import glob
import os
import plistlib
import signal
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
AU_DUMP = os.path.join(HERE, "au_dump")

COMPONENT_DIRS = [
    "/Library/Audio/Plug-Ins/Components",
    os.path.expanduser("~/Library/Audio/Plug-Ins/Components"),
]


def components():
    """Yield (name, type, subtype, manufacturer, bundle) for every AU."""
    seen = set()
    for d in COMPONENT_DIRS:
        for bundle in sorted(glob.glob(os.path.join(d, "*.component"))):
            info = os.path.join(bundle, "Contents", "Info.plist")
            if not os.path.exists(info):
                continue
            try:
                with open(info, "rb") as fh:
                    pl = plistlib.load(fh)
            except Exception:
                continue
            for ac in pl.get("AudioComponents", []) or []:
                key = (ac.get("type"), ac.get("subtype"), ac.get("manufacturer"))
                if key in seen:
                    continue
                seen.add(key)
                yield (ac.get("name", "?"), ac["type"], ac["subtype"],
                       ac["manufacturer"], os.path.basename(bundle))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "param-maps"))
    ap.add_argument("--only", default=None,
                    help="substring filter on name/subtype/manufacturer")
    ap.add_argument("--timeout", type=float, default=25.0)
    ap.add_argument("--resume", action="store_true",
                    help="skip plug-ins whose map file already has parameters")
    args = ap.parse_args(argv)

    if not os.path.exists(AU_DUMP):
        print("build it first: clang -O2 -o tools/au_dump tools/au_dump.c "
              "-framework AudioToolbox -framework CoreFoundation", file=sys.stderr)
        return 2
    os.makedirs(args.out, exist_ok=True)

    rows, ok, empty = [], 0, 0
    for name, typ, sub, man, bundle in components():
        if args.only and args.only.lower() not in (name + sub + man + bundle).lower():
            continue
        dest = os.path.join(args.out, "%s_%s.txt" % (man, sub))
        if args.resume and os.path.exists(dest):
            with open(dest, "r", errors="replace") as fh:
                if any(ln.startswith("  ") for ln in fh):
                    continue
        # Write to a FILE, not a pipe: an out-of-process plug-in can leave a
        # grandchild holding the pipe open, which deadlocks communicate() past
        # its own timeout.  A file handle has no such problem.
        fd, tmp = tempfile.mkstemp(prefix="aumap")
        os.close(fd)
        text = ""
        with open(tmp, "wb") as out:
            p = subprocess.Popen([AU_DUMP, typ, sub, man], stdout=out,
                                 stderr=subprocess.DEVNULL,
                                 stdin=subprocess.DEVNULL, start_new_session=True)
            try:
                p.wait(timeout=args.timeout)
            except subprocess.TimeoutExpired:
                try:
                    os.killpg(os.getpgid(p.pid), signal.SIGKILL)
                except Exception:
                    p.kill()
                p.wait()
        try:
            with open(tmp, "r", errors="replace") as fh:
                text = fh.read()
        finally:
            os.unlink(tmp)
        with open(dest, "w") as fh:
            fh.write(text)
        n = sum(1 for ln in text.splitlines() if ln.startswith("  "))
        if n:
            ok += 1
            rows.append((man, sub, name, n, dest))
            print("  %-6s %-6s %-34s %4d params" % (man, sub, name[:34], n))
        else:
            empty += 1
            print("  %-6s %-6s %-34s    -- (no parameter list)" % (man, sub, name[:34]))

    print()
    print("%d mapped, %d unreadable, %d files in %s" % (ok, empty, ok + empty, args.out))
    with open(os.path.join(args.out, "INDEX.md"), "w") as fh:
        fh.write("# Audio Unit parameter maps\n\n"
                 "Generated by `tools/dump_all_maps.py` on this machine. Each row is one\n"
                 "installed Audio Unit; the linked file lists its parameters **in the order\n"
                 "the plug-in reports them**, which is the order its state is written in.\n\n"
                 "| manufacturer | subtype | plug-in | params | map |\n|---|---|---|---|---|\n")
        for man, sub, name, n, dest in sorted(rows):
            fh.write("| `%s` | `%s` | %s | %d | [%s](%s) |\n"
                     % (man, sub, name, n, os.path.basename(dest),
                        os.path.basename(dest)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
